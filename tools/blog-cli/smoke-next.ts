/** Real Next.js release smoke test. Everything except dependencies is disposable. */
import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile, realpath, rm, symlink, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Document } from 'yaml';
import { readSourcePost, scanContent, splitDocument } from '../../src/lib/blog/content';
import { exists, walk } from '../../src/lib/blog/files';
import { defaultConfig } from '../../src/lib/blog/schema';
import { buildRelease, verifyPackage } from './site';
import { createPlan } from './plan';
import { codeBaseline, saveSnapshot } from './snapshot';
import { newPost } from './writing';
import { run } from './process';
import sharp from 'sharp';
import { githubTarget, preparePagesBundle } from './pages';
import { buildPages } from './pages-build';
import { newSeries, editSeries, saveSeriesSnapshot } from './series';
import { readSourceSeries } from '../../src/lib/blog/series';

async function smoke() {
  const project = fileURLToPath(new URL('../../', import.meta.url));
  const root = await realpath(await mkdtemp(path.join(os.tmpdir(), 'sachi-next-smoke-')));
  try {
    for (const file of ['src', 'tools', 'public/assets', 'package.json', 'package-lock.json', 'tsconfig.json', 'next.config.ts', 'next-env.d.ts']) await cp(path.join(project, file), path.join(root, file), { recursive: true });
    await symlink(path.join(project, 'node_modules'), path.join(root, 'node_modules'), 'dir');
    const config = defaultConfig('Asia/Shanghai');
    // The real writing repository must never enter frozen code or the public Pages source.
    await mkdir(path.join(root, '.blog-store/.git'), { recursive: true });
    await writeFile(path.join(root, '.blog-store/.git/PRIVATE_REPOSITORY_METADATA'), 'must remain private');
    config.siteUrl = 'https://sachi-smoke.example.org';
    const profileFile = path.join(root, 'src/config/profile.json');
    const profile = JSON.parse(await readFile(profileFile, 'utf8'));
    profile.name = '验收作者'; profile.signature = '验收签名'; profile.bio = '验收简介';
    await writeFile(profileFile, JSON.stringify(profile));
    const series = await newSeries(root, { category: 'learn', title: 'CLI 系列阅读验收', slug: 'cli-series', description: '冻结的公开系列简介' });
    const created = await newPost(root, config, { category: '蘸豆！！', title: 'CLI 真文章环绕验收', slug: 'cli-integration', series: { id: series.id, order: 1 } });
    const file = path.join(root, created.file); const directory = path.dirname(file);
    await cp(path.join(root, 'public/assets/tea-cup.webp'), path.join(directory, 'assets/cup.webp'));
    await cp(path.join(root, 'public/assets/tea-cup-contour.json'), path.join(directory, 'assets/cup-contour.json'));
    const document = new Document(splitDocument(await readFile(file, 'utf8')).data);
    document.set('cover', './assets/cup.webp');
    document.set('flow', { image: './assets/cup.webp', contour: './assets/cup-contour.json', defaultX: 0.53, defaultY: 86 });
    let body = '第一段用于检查真实环绕。\n\n第二段需要完整保留，在移动端能够回到普通排版。\n\n![杯子](./assets/cup.webp)\n\n## 正文\n\n普通 **Markdown** 与表格。\n\n| 标题 | 内容 |\n| --- | --- |\n| 测试 | 完整正文 |\n';
    body += '\n```ts\nconst note = "<静态>&";\n\nconsole.log(note);\n```\n';
    body += `\n[回到系列目录](series:${series.id})\n`;
    const hasFfmpeg = await run(['ffmpeg', '-version'], { cwd: root }).then(() => true).catch(() => false);
    if (hasFfmpeg) {
      await run(['ffmpeg', '-v', 'error', '-nostdin', '-y', '-f', 'lavfi', '-i', 'color=c=green:s=32x24:d=0.3', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', path.join(directory, 'assets/demo.mp4')], { cwd: root });
      body += '\n![短视频](./assets/demo.mp4)\n';
    }
    await writeFile(file, `---\n${document.toString()}---\n\n${body}`);
    const draft = await newPost(root, config, { category: '生活旁白', title: '不可发布草稿', slug: 'private-draft' });
    const marker = `PRIVATE_CLI_SMOKE_DRAFT_${draft.id}`;
    await writeFile(path.join(root, draft.file), (await readFile(path.join(root, draft.file), 'utf8')).replace('在这里写正文。', marker));
    await mkdir(path.join(root, 'public', 'media'), { recursive: true });
    await writeFile(path.join(root, 'public', 'media', 'never-export.txt'), marker);
    const source = await readSourcePost(root, created.file, config);
    const generic = await newPost(root, config, { category: '生活旁白', title: '横向插画自动环绕', slug: 'generic-flow' });
    const genericFile = path.join(root, generic.file);
    const genericImage = await sharp({ create: { width: 600, height: 300, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
      .composite([{ input: Buffer.from('<svg width="600" height="300"><ellipse cx="300" cy="150" rx="240" ry="120" fill="#667553"/></svg>') }]).png().toBuffer();
    await writeFile(path.join(path.dirname(genericFile), 'assets/landscape.png'), genericImage);
    const genericDocument = new Document(splitDocument(await readFile(genericFile, 'utf8')).data);
    genericDocument.set('flow', { image: './assets/landscape.png', width: 280, defaultX: 0.5, defaultY: 60 });
    await writeFile(genericFile, `---\n${genericDocument.toString()}---\n\n${'一张横向插画，文字沿透明轮廓排版，普通正文也完整保留。'.repeat(30)}\n\n![横向插画](./assets/landscape.png)\n\n## 正文\n\n后文不参与环绕。`);
    const genericSource = await readSourcePost(root, generic.file, config);
    const third = await newPost(root, config, { category: 'learn', title: '公开的第三章', slug: 'series-third', series: { id: series.id, order: 3 } });
    const thirdSource = await readSourcePost(root, third.file, config);
    await newPost(root, config, { category: 'learn', title: 'PRIVATE_SERIES_CHAPTER', slug: 'series-private-second', series: { id: series.id, order: 2 } });
    const seriesSource = await readSourceSeries(root, series.file);
    const baseline = await codeBaseline(root, config, true);
    await saveSnapshot(root, config, source);
    await saveSnapshot(root, config, genericSource);
    await saveSnapshot(root, config, thirdSource);
    await saveSeriesSnapshot(root, seriesSource);
    const plan = createPlan(null, [source, genericSource, thirdSource], (await scanContent(root, config)).posts, baseline, [], new Date(), [seriesSource]);
    // Later working edits must not leak into the frozen build's profile.
    await writeFile(profileFile, JSON.stringify({ ...profile, name: '不应混入的后续名字' }));
    await editSeries(root, config, series.id, { description: 'PRIVATE_SERIES_INTRO' });
    const built = await buildRelease(root, config, plan.manifest, { echo: true });
    await verifyPackage(built.directory);
    const site = path.join(built.directory, 'site');
    const html = await readFile(path.join(site, 'article', created.slug, 'index.html'), 'utf8');
    assert(html.includes('CLI 真文章环绕验收')); assert(html.includes('flow-block')); assert(html.includes('第二段需要完整保留'));
    assert(html.includes('href="/series/cli-series/"')); assert(html.includes('href="/article/series-third/"'));
    const seriesHtml = await readFile(path.join(site, 'series/cli-series/index.html'), 'utf8');
    assert(seriesHtml.includes('冻结的公开系列简介')); assert(seriesHtml.replace(/<!--[\s\S]*?-->/g, '').includes('已发布 2 篇'));
    assert(seriesHtml.indexOf('CLI 真文章环绕验收') < seriesHtml.indexOf('公开的第三章'));
    assert(!seriesHtml.includes('PRIVATE_SERIES')); assert(!await exists(path.join(site, 'article/series-private-second')));
    assert(html.includes('class="heading-link" href="#%E6%AD%A3%E6%96%87"'));
    assert(/<button[^>]*class="code-copy"[^>]*hidden=""[^>]*disabled=""/.test(html));
    const codeHtml = /<pre[^>]*><code[^>]*class="[^"]*\blanguage-ts\b[^"]*"[^>]*>([\s\S]*?)<\/code><\/pre>/.exec(html);
    assert(codeHtml, 'TypeScript code remains a real pre/code block.');
    const codeText = codeHtml[1].replace(/<[^>]*>/g, '').replaceAll('&quot;', '"').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&');
    assert.equal(codeText, 'const note = "<静态>&";\n\nconsole.log(note);\n');
    assert(html.includes('avatar-half')); assert(html.includes(`/versions/${plan.manifest.releaseId}/_next/`));
    assert(html.includes('验收作者')); assert(!html.includes('不应混入的后续名字'));
    assert(html.includes('<link rel="canonical" href="https://sachi-smoke.example.org/article/cli-integration/"'));
    assert(html.includes('property="og:type" content="article"')); assert(html.includes('name="twitter:card"'));
    const structured = JSON.parse(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(html)![1]);
    assert.equal(structured['@graph'][0].author.name, '验收作者');
    assert.equal(structured['@graph'][0].datePublished, plan.manifest.entries[0].publishedAt);
    assert.equal(structured['@graph'][0].dateModified, plan.manifest.entries[0].updatedAt);
    const home = await readFile(path.join(site, 'index.html'), 'utf8');
    assert(home.includes('cover-title-text')); assert(home.includes('验收签名')); assert(home.includes('验收简介'));
    assert(!home.includes('<img alt="" width="590"'));
    assert(home.includes('class="home-avatar-link" href="/about/"'));
    assert(html.includes('class="author-about-link" href="/about/"'));
    const about = await readFile(path.join(site, 'about/index.html'), 'utf8');
    assert(about.includes('验收作者')); assert(!about.includes('不应混入的后续名字'));
    assert(!about.includes('不可发布草稿')); assert(!about.includes('PRIVATE_SERIES_CHAPTER'));
    assert(about.includes('writing-calendar'));
    assert(about.includes('CLI 真文章环绕验收')); assert(about.includes('公开的第三章'));
    assert(about.includes(`/versions/${plan.manifest.releaseId}/_next/static/media/bamboo-left`));
    const genericHtml = await readFile(path.join(site, 'article/generic-flow/index.html'), 'utf8');
    assert(genericHtml.includes('alt="横向插画"')); assert(genericHtml.includes('width="600" height="300"'));
    const contour = built.manifest.assets[generic.id]['./assets/landscape.png'].contour;
    assert(contour?.startsWith('/media/')); assert(await exists(path.join(site, contour!.slice(1))));
    const sitemap = await readFile(path.join(site, 'sitemap.xml'), 'utf8');
    assert(sitemap.includes('/article/cli-integration/')); assert(sitemap.includes('/article/generic-flow/'));
    assert(sitemap.includes('/series/cli-series/'));
    assert(!/private-draft|__empty__|example\.com/.test(sitemap));
    assert((await readFile(path.join(site, 'robots.txt'), 'utf8')).includes('Sitemap: https://sachi-smoke.example.org/sitemap.xml'));
    if (hasFfmpeg) { assert(html.includes('<video')); assert(html.includes('controls')); assert(html.includes('poster=')); }
    assert(!await exists(path.join(site, 'article', 'private-draft')));
    assert(!await exists(path.join(site, 'media', 'never-export.txt')));
    for (const name of await walk(site)) if (/\.(?:html|js|json|txt)$/.test(name)) assert(!(await readFile(path.join(site, name), 'utf8')).includes(marker), `草稿泄漏：${name}`);
    const pagesRoot = path.join(root, 'pages-export'); await mkdir(pagesRoot);
    const target = githubTarget('https://github.com/sachi-smoke/sachi.git');
    await preparePagesBundle(root, built.directory, built.manifest, target, pagesRoot);
    assert(!await exists(path.join(pagesRoot, '.blog-store')));
    assert(!await exists(path.join(built.directory, '.git')));
    await symlink(path.join(project, 'node_modules'), path.join(pagesRoot, 'node_modules'), 'dir');
    const pagesOutput = await buildPages(pagesRoot);
    const pagesHtml = await readFile(path.join(pagesOutput, 'article/cli-integration/index.html'), 'utf8');
    const pagesAbout = await readFile(path.join(pagesOutput, 'about/index.html'), 'utf8');
    assert(pagesAbout.includes('href="/sachi/article/cli-integration/"'));
    assert(pagesAbout.includes(`/sachi/versions/${plan.manifest.releaseId}/_next/static/media/bamboo-left`));
    assert(pagesHtml.includes('class="author-about-link" href="/sachi/about/"'));
    assert(pagesHtml.includes('href="/sachi/contents/"'));
    assert(pagesHtml.includes('href="/sachi/series/cli-series/"')); assert(pagesHtml.includes('href="/sachi/article/series-third/"'));
    assert((await readFile(path.join(pagesOutput, 'series/cli-series/index.html'), 'utf8')).includes('冻结的公开系列简介'));
    assert(pagesHtml.includes('/sachi/media/')); assert(pagesHtml.includes(`/sachi/versions/${plan.manifest.releaseId}/_next/`));
    assert(pagesHtml.includes('rel="canonical" href="https://sachi-smoke.github.io/sachi/article/cli-integration/"'));
    assert(pagesHtml.includes('flow-block')); assert(pagesHtml.includes('code-copy')); assert(pagesHtml.includes('avatar-half'));
    assert(pagesHtml.includes('验收作者')); assert(!pagesHtml.includes('不应混入的后续名字'));
    assert((await readFile(path.join(pagesOutput, 'sitemap.xml'), 'utf8')).includes('https://sachi-smoke.github.io/sachi/article/cli-integration/'));
    assert((await readFile(path.join(pagesOutput, 'robots.txt'), 'utf8')).includes('https://sachi-smoke.github.io/sachi/sitemap.xml'));
    assert(!await exists(path.join(pagesOutput, 'article/private-draft')));
    for (const name of await walk(pagesOutput)) if (/\.(?:html|js|json|txt)$/.test(name)) assert(!(await readFile(path.join(pagesOutput, name), 'utf8')).includes(marker), `Pages 草稿泄漏：${name}`);
    console.log('PASS: portable Pages source bundle and project subpath, frozen media/identity, native links, SEO, flow and draft exclusion. No live GitHub connection.');
    console.log('PASS: real Next release, heading permalinks + copyable code, manual + automatic generic flow, frozen configurable identity, canonical/OG/Twitter/JSON-LD/sitemap/robots, hashed avatars, short video, and draft exclusion. No remote writes.');
  } finally { await rm(root, { recursive: true, force: true }); }
}
smoke().catch((error: unknown) => { console.error(error); process.exitCode = 1; });
